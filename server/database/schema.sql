-- Pangisda – PostgreSQL schema (see docs/ERD.md)
-- Run with `npm run db:setup`, which also loads the sample data.
-- WARNING: this drops and recreates every table, so existing data is lost.

DROP TABLE IF EXISTS favorites, catches, spot_species, species, fishing_spots, users CASCADE;
DROP TYPE IF EXISTS user_role, water_type, access_level, fishing_method;

CREATE TYPE user_role      AS ENUM ('angler', 'admin');
CREATE TYPE water_type     AS ENUM ('saltwater', 'freshwater', 'brackish');
CREATE TYPE access_level   AS ENUM ('easy', 'moderate', 'hard');
CREATE TYPE fishing_method AS ENUM ('rod_and_reel', 'handline', 'fly_fishing', 'spearfishing', 'cast_net');

CREATE TABLE users (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name     VARCHAR(60)  NOT NULL,
  username      VARCHAR(20)  NOT NULL UNIQUE,
  email         VARCHAR(120) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          user_role    NOT NULL DEFAULT 'angler',
  created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE fishing_spots (
  id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         VARCHAR(80)  NOT NULL,
  municipality VARCHAR(60)  NOT NULL,
  province     VARCHAR(60)  NOT NULL,
  water_type   water_type   NOT NULL,
  latitude     DECIMAL(9,6) NOT NULL CHECK (latitude BETWEEN 4 AND 22),
  longitude    DECIMAL(9,6) NOT NULL CHECK (longitude BETWEEN 116 AND 127),
  best_time    VARCHAR(80),
  access_level access_level NOT NULL DEFAULT 'moderate',
  description  TEXT         NOT NULL CHECK (char_length(description) >= 20),
  created_by   INT          REFERENCES users (id) ON DELETE SET NULL,
  created_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX fishing_spots_province_idx   ON fishing_spots (province);
CREATE INDEX fishing_spots_water_type_idx ON fishing_spots (water_type);

CREATE TABLE species (
  id                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  common_name       VARCHAR(80)  NOT NULL,
  local_name        VARCHAR(60)  NOT NULL,
  scientific_name   VARCHAR(80)  NOT NULL UNIQUE,
  habitat           water_type   NOT NULL,
  is_protected      BOOLEAN      NOT NULL DEFAULT FALSE,
  conservation_note VARCHAR(255),
  image_url         VARCHAR(255),
  image_credit      VARCHAR(255)
);

-- Junction table: which species are found at which spot (M:N)
CREATE TABLE spot_species (
  spot_id    INT NOT NULL REFERENCES fishing_spots (id) ON DELETE CASCADE,
  species_id INT NOT NULL REFERENCES species (id) ON DELETE CASCADE,
  PRIMARY KEY (spot_id, species_id)
);

CREATE TABLE catches (
  id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INT            NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  spot_id    INT            NOT NULL REFERENCES fishing_spots (id) ON DELETE RESTRICT,
  species_id INT            NOT NULL REFERENCES species (id) ON DELETE RESTRICT,
  weight_kg  DECIMAL(6,2)   NOT NULL CHECK (weight_kg > 0 AND weight_kg <= 500),
  length_cm  DECIMAL(5,1)   CHECK (length_cm BETWEEN 1 AND 400),
  caught_at  DATE           NOT NULL,
  method     fishing_method NOT NULL,
  bait       VARCHAR(60),
  released   BOOLEAN        NOT NULL DEFAULT FALSE,
  notes      VARCHAR(500),
  created_at TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX catches_user_id_idx ON catches (user_id);
CREATE INDEX catches_spot_id_idx ON catches (spot_id);

-- Planned for the Final (saved spots are still kept in a browser cookie for now)
CREATE TABLE favorites (
  user_id    INT         NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  spot_id    INT         NOT NULL REFERENCES fishing_spots (id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, spot_id)
);
